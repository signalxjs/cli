#!/usr/bin/env node
/**
 * gen-versions.mjs — the scaffolder's single source of version truth.
 *
 * Writes packages/cli/src/create/versions.ts from:
 *   - the pnpm catalog (pnpm-workspace.yaml): the core line (`@sigx/vite`,
 *     shared by every package in CORE_PACKAGES) and the companion lines
 *     (`@sigx/router`, `@sigx/ssg`, …);
 *   - packages/cli/package.json: `@sigx/cli`'s own single-minor range, for
 *     templates whose scripts run `sigx …`;
 *   - scripts/lib/template-versions.json: third-party pins.
 *
 * Template pins used to be hand-copied into twelve package.json files and
 * drifted several minors behind the catalog (signalxjs/cli#91) — a scaffolded
 * app then resolved two copies of @sigx/reactivity and reactivity silently
 * broke. Generating the file makes `pnpm sync:core` flow into templates, and
 * `--check` (wired into `pnpm verify:catalog`) fails CI when the committed
 * file is stale.
 *
 *   node scripts/gen-versions.mjs           # write
 *   node scripts/gen-versions.mjs --check   # exit 1 if the file would change
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CORE_PACKAGES } from './lib/core-deps.mjs';
import { readCatalog } from './lib/catalog.mjs';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(repoRoot, 'packages', 'cli', 'src', 'create', 'versions.ts');
const check = process.argv.includes('--check');

const catalog = readCatalog(repoRoot);
const core = catalog['@sigx/vite'];
if (!core) {
    console.error('gen-versions: catalog["@sigx/vite"] missing in pnpm-workspace.yaml');
    process.exit(1);
}

const cliPkg = JSON.parse(readFileSync(join(repoRoot, 'packages', 'cli', 'package.json'), 'utf8'));
const [major, minor] = cliPkg.version.split('.');
const cliRange = `^${major}.${minor}.0`;

const companions = Object.fromEntries(
    Object.entries(catalog).filter(([name]) => !CORE_PACKAGES.has(name)),
);
const thirdParty = JSON.parse(readFileSync(join(repoRoot, 'scripts', 'lib', 'template-versions.json'), 'utf8'));
delete thirdParty['//'];

const record = (obj) =>
    '{\n' + Object.entries(obj).map(([k, v]) => `    '${k}': '${v}',`).join('\n') + '\n}';

const content = `/**
 * GENERATED by scripts/gen-versions.mjs — do not edit by hand.
 *
 * Sources: the pnpm catalog (pnpm-workspace.yaml), packages/cli/package.json,
 * and scripts/lib/template-versions.json. Regenerate with \`pnpm gen:versions\`;
 * \`pnpm verify:catalog\` fails when this file is stale.
 */

/** The core line: every package published from signalxjs/core shares it. */
export const SIGX_CORE = '${core}';

/** \`@sigx/cli\`'s own single-minor range, for templates whose scripts run \`sigx\`. */
export const SIGX_CLI = '${cliRange}';

/** Packages on the core line (mirrors scripts/lib/core-deps.mjs). */
export const SIGX_CORE_PACKAGES: ReadonlySet<string> = new Set([
${[...CORE_PACKAGES].map((p) => `    '${p}',`).join('\n')}
]);

/** Companion packages with their own release lines. */
export const SIGX_COMPANIONS: Readonly<Record<string, string>> = ${record(companions)};

/** Third-party pins. */
export const THIRD_PARTY: Readonly<Record<string, string>> = ${record(thirdParty)};
`;

let current = '';
try { current = readFileSync(outFile, 'utf8'); } catch { /* first run */ }

// Compare newline-insensitively: a Windows checkout with core.autocrlf
// rewrites the committed file to CRLF, which is not staleness.
const same = current.replace(/\r\n/g, '\n') === content;

if (check) {
    if (!same) {
        console.error(`gen-versions --check FAILED: ${outFile} is stale — run \`pnpm gen:versions\` and commit the result.`);
        process.exit(1);
    }
    console.log('gen-versions OK — versions.ts matches the catalog.');
} else if (!same) {
    writeFileSync(outFile, content);
    console.log(`✓ wrote ${outFile}`);
} else {
    console.log('versions.ts already up to date.');
}
